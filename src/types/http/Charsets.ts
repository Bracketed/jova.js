/**
 * @name Charset
 * @description
 * Common character sets used in HTTP.
 *
 * @module Types
 * @memberof Types
 * @enum Charset
 */
export enum Charset {
	/**
	 * @name ASCII
	 * @description
	 * ASCII character set.
	 * @see {@link https://en.wikipedia.org/wiki/ASCII ASCII on Wikipedia}
	 * @type string
	 */
	ASCII = 'US-ASCII',

	/**
	 * @name ISO/IEC 8859-1
	 * @description
	 * ISO/IEC 8859-1 Latin-1 character set.
	 * @see {@link https://en.wikipedia.org/wiki/ISO/IEC_8859-1 ISO/IEC 8859-1 Latin-1 on Wikipedia}
	 * @type string
	 */
	ISO_8859_1 = 'ISO-8859-1',

	/**
	 * @name ISO/IEC 8859-2
	 * @description
	 * ISO/IEC 8859-2 Latin-2 Central European character set.
	 * @see {@link https://en.wikipedia.org/wiki/ISO/IEC_8859-2 ISO/IEC 8859-2 Latin-2 Central European on Wikipedia}
	 * @type string
	 */
	ISO_8859_2 = 'ISO-8859-2',

	/**
	 * @name ISO/IEC 8859-3
	 * @description
	 * ISO/IEC 8859-3 Latin-3 South European character set.
	 * @see {@link https://en.wikipedia.org/wiki/ISO/IEC_8859-3 ISO/IEC 8859-3 Latin-3 South European on Wikipedia}
	 * @type string
	 */
	ISO_8859_3 = 'ISO-8859-3',

	/**
	 * @name ISO/IEC 8859-4
	 * @description
	 * ISO/IEC 8859-4 Latin-4 North European character set.
	 * @see {@link https://en.wikipedia.org/wiki/ISO/IEC_8859-4 ISO/IEC 8859-4 Latin-4 North European on Wikipedia}
	 * @type string
	 */
	ISO_8859_4 = 'ISO-8859-4',

	/**
	 * @name ISO/IEC 8859-5
	 * @description
	 * ISO/IEC 8859-5 Latin/Cyrillic character set.
	 * @see {@link https://en.wikipedia.org/wiki/ISO/IEC_8859-5 ISO/IEC 8859-5 Latin/Cyrillic on Wikipedia}
	 * @type string
	 */
	ISO_8859_5 = 'ISO-8859-5',

	/**
	 * @name ISO/IEC 8859-6
	 * @description
	 * ISO/IEC 8859-6 Latin/Arabic character set.
	 * @see {@link https://en.wikipedia.org/wiki/ISO/IEC_8859-6 ISO/IEC 8859-6 Latin/Arabic on Wikipedia}
	 * @type string
	 */
	ISO_8859_6 = 'ISO-8859-6',

	/**
	 * @name ISO/IEC 8859-7
	 * @description
	 * ISO/IEC 8859-7 Latin/Greek character set.
	 * @see {@link https://en.wikipedia.org/wiki/ISO/IEC_8859-7 ISO/IEC 8859-7 Latin/Greek on Wikipedia}
	 * @type string
	 */
	ISO_8859_7 = 'ISO-8859-7',

	/**
	 * @name ISO/IEC 8859-8
	 * @description
	 * ISO/IEC 8859-8 Latin/Hebrew character set.
	 * @see {@link https://en.wikipedia.org/wiki/ISO/IEC_8859-8 ISO/IEC 8859-8 Latin/Hebrew on Wikipedia}
	 * @type string
	 */
	ISO_8859_8 = 'ISO-8859-8',

	/**
	 * @name ISO/IEC 8859-9
	 * @description
	 * ISO/IEC 8859-9 Latin-5 Turkish character set.
	 * @see {@link https://en.wikipedia.org/wiki/ISO/IEC_8859-9 ISO/IEC 8859-9 Latin-5 Turkish on Wikipedia}
	 * @type string
	 */
	ISO_8859_9 = 'ISO-8859-9',

	/**
	 * @name UTF-8
	 * @description
	 * UTF-8 character set (Universal Character Set Transformation Format).
	 * @see {@link https://en.wikipedia.org/wiki/UTF-8 UTF-8 on Wikipedia}
	 * @type string
	 */
	UTF_8 = 'UTF-8',

	/**
	 * @name UTF-16
	 * @description
	 * UTF-16 character set (16-bit Unicode Transformation Format).
	 * @see {@link https://en.wikipedia.org/wiki/UTF-16 UTF-16 on Wikipedia}
	 * @type string
	 */
	UTF_16 = 'UTF-16',
}
